void UI::draw()
{
  initUI();
  setFont(FONT_UI);
  this->firstPage();
  do
  {
    switch (Page::getCurrentPage())
    {
    case MAIN_PAGE:
      main();
      break;
    case SELECT_SETTINGS:
      menuUI->draw();
      break;
    default:
      break;
    }
  } while (this->nextPage());
}

void UI::initUI()
{
  snprintf(tempText, sizeof(tempText), "Temperature: %d", static_cast<int>(_temperature));
  // snprintf(resText, sizeof(resText), "Resistance: %.2f", static_cast<double>(_resistance));
  setFloatText(resText, sizeof(resText), "Resistance", _resistance);
  snprintf(acpText, sizeof(acpText), "ACP: %d", _acp);
}

void UI::startWindow()
{
  setFont(FONT_START);
  this->firstPage();
  do
  {
    drawCentered("Factory IRBIS", 0, 25);
    this->drawXBMP(CENTER_X / 2, CENTER_Y / 2, 70, 40, epd_bitmap_Capture);
  } while (this->nextPage());
  delay(START_MENU_DURATION);
}

IDisplay &UI::setAcp(int acp)
{
  _acp = acp;
  return *this;
}

IDisplay &UI::setRes(float v)
{
  _resistance = v;
  return *this;
}

int UI::drawCentered(const char *text, int padding_top, int padding_bottom, int padding_left, int padding_right)
{
  int x = (OLED_WIDTH - this->getStrWidth(text)) / 2;
  int y = (OLED_HEIGHT + this->getFontAscent()) / 2;
  this->drawStr(x + padding_left - padding_right, y + padding_top - padding_bottom, text);
  return y;
}

void UI::clearDisplay()
{
  OLED_CLASS::clear();
}

void UI::setFont(UiFont font)
{
  switch (font)
  {
  case FONT_START:
    OLED_CLASS::setFont(START_FONT);
    break;
  case FONT_UI:
  default:
    OLED_CLASS::setFont(FONT);
    break;
  }
}

void UI::drawStr(int x, int y, const char *str)
{
  OLED_CLASS::drawStr(x, y, str);
}

int UI::getStrWidth(const char *str)
{
  return OLED_CLASS::getStrWidth(str);
}

int UI::getFontHeight()
{
  return OLED_CLASS::getFontAscent();
}

