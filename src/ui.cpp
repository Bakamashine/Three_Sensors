UI::UI()
    : OLED_CLASS(U8G2_R0, /* reset=*/U8X8_PIN_NONE)
{
  menuUI = new MenuUI(this);
}

UI::~UI() { delete menuUI; }

void UI::initDisplay(int sda, int scl)
{
  (void)sda;
  (void)scl;
  OLED_CLASS::begin();
  clearDisplay();
}

void UI::initUI() {}

MenuUI &UI::getMenuUI()
{
  return *menuUI;
}

IDisplay &UI::setTemperature(float temp)
{
  this->_temperature = temp;
  return *this;
}

void UI::main()
{
  // columns
  RAW_WRITE_ROW(U8G2_FIRST_ROW, nullptr, PREVIEW_ACP_TEXT, PREVIEW_COLUMN_TEMP, this);
  // rows

  // main sensor
  if (_mainSensor)
    AT_WRITE_ROW(U8G2_SECOND_ROW, PREVIEW_TEMP, *_mainSensor);

  // first reserve sensor
  if (_firstReserveSensor)
    AT_WRITE_ROW(U8G2_THIRD_ROW, PREVIEW_FIRST_RESERVE, *_firstReserveSensor);

  // second reserve sensor
  if (_secondReserveSensor)
    AT_WRITE_ROW(U8G2_FOURTH_ROW, PREVIEW_SECOND_RESERVE, *_secondReserveSensor);

  // street sensor
  if (_streetSensor)
    AT_WRITE_ROW(U8G2_FIFTH_ROW, PREVIEW_STREET, *_streetSensor);
}

void UI::draw()
{
  // initUI();
  setFont(FONT_UI);
  this->firstPage();
  do
  {
    switch (Page::getCurrentPage())
    {
    case MAIN_PAGE:
      main();
      break;
    case SETTINGS:
      menuUI->draw();
      break;
    default:
      break;
    }
  } while (this->nextPage());
}

void UI::startWindow()
{
  setFont(FONT_START);
  this->firstPage();
  do
  {
    drawCentered("Factory IRBIS", 0, 25);
    this->drawXBMP(CENTER_X / 2, CENTER_Y / 2, 70, 40, epd_bitmap_Capture);
  } while (this->nextPage());
  delay(START_MENU_DURATION);
}

